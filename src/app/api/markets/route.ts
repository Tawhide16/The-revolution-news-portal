// Helper to add micro realistic fluctuations to simulate real-time market ticks
function addMicroFluctuations(stocks: typeof BASE_STOCKS, indices: typeof BASE_INDICES) {
  // Rank stocks by market cap descending
  const sortedStocks = [...stocks].sort((a, b) => b.marketCapNumber - a.marketCapNumber);

  const rankedStocks: StockQuote[] = sortedStocks.map((stock, index) => {
    // Generate subtle +/- 0.15% fluctuation
    const factor = 1 + (Math.sin(Date.now() / 15000 + index) * 0.003);
    const newPrice = Number((stock.price * factor).toFixed(2));
    const newChange = Number((stock.change + (newPrice - stock.price)).toFixed(2));
    const newChangePercent = Number(((newChange / (newPrice - newChange)) * 100).toFixed(2));

    const spark = [...stock.sparkline];
    spark[spark.length - 1] = newPrice;

    return {
      ...stock,
      rank: index + 1,
      price: newPrice,
      change: newChange,
      changePercent: newChangePercent,
      sparkline: spark,
    };
  });

  const updatedIndices: MarketIndex[] = indices.map((idx, i) => {
    const factor = 1 + (Math.cos(Date.now() / 20000 + i) * 0.0015);
    const newVal = Number((idx.value * factor).toFixed(2));
    const newChange = Number((idx.change + (newVal - idx.value)).toFixed(2));
    const newPct = Number(((newChange / (newVal - newChange)) * 100).toFixed(2));
    return {
      ...idx,
      value: newVal,
      change: newChange,
      changePercent: newPct,
    };
  });

  return { rankedStocks, updatedIndices };
}

